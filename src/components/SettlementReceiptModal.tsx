import React from 'react';
import { BadgeCheck, CheckCircle2, Copy, ImageDown, Loader2, X } from 'lucide-react';
import { ClinicSettings, Settlement } from '../types';
import { exportSettlementAsImage } from '../utils/settlementImageExport';
import { displayDateKey, weekdayNameDateKey } from '../utils/dateUtils';
import {
  isSettlementWithDue,
  settlementOutcomeText,
  writtenOffAmountOf,
} from '../utils/settlementResolution';

interface SettlementReceiptModalProps {
  settlement: Settlement | null;
  settings: ClinicSettings;
  onClose: () => void;
  showToast: (title: string, desc?: string, type?: 'success' | 'info' | 'warning' | 'error') => void;
}

export const SettlementReceiptModal: React.FC<SettlementReceiptModalProps> = ({
  settlement,
  settings,
  onClose,
  showToast,
}) => {
  const [isExportingImage, setIsExportingImage] = React.useState<boolean>(false);

  if (!settlement) return null;

  const currency = settings.currencySymbol || '৳';
  const formatNumber = (num: number) => new Intl.NumberFormat('en-BD').format(Math.round(num));

  // Confirmation recorded when the batch was closed: either a due amount was
  // carried forward, or the batch was cleared with a round-figure waiver.
  const writtenOff = writtenOffAmountOf(settlement);
  const hasDue = isSettlementWithDue(settlement);
  const outcomeLine = settlementOutcomeText(settlement, currency, formatNumber);

  const handleCopySummary = async () => {
    const text = `
DENTAL CLINIC SETTLEMENT RECEIPT
--------------------------------------
Settlement ID: ${settlement.settlementId}
Date: ${weekdayNameDateKey(settlement.settlementDate)} ${displayDateKey(settlement.settlementDate)}
Clinic: ${settings.clinicName}
Doctor: ${settings.doctorName || '—'}
Period: ${weekdayNameDateKey(settlement.periodFrom)} ${displayDateKey(settlement.periodFrom)} to ${weekdayNameDateKey(settlement.periodTo)} ${displayDateKey(settlement.periodTo)}
Patients Settled: ${settlement.patientCount}

FINANCIAL BREAKDOWN:
- Period ${settings.sharePercentage || 40}% Share: ${currency} ${formatNumber(settlement.periodShare)}
- Carried-over Due: ${currency} ${formatNumber(settlement.previousDue)}
- Total Payable: ${currency} ${formatNumber(settlement.totalPayable)}
- Amount Paid by Clinic: ${currency} ${formatNumber(settlement.amountReceived)}
- Due Carried Forward: ${currency} ${formatNumber(settlement.dueBalance)}
- Confirmation: ${outcomeLine}
${settlement.remarks ? `Notes: ${settlement.remarks}` : ''}
--------------------------------------
Generated by HishApp (hishapp1.web.app)
    `.trim();

    try {
      await navigator.clipboard.writeText(text);
      showToast('Copied to Clipboard', 'Settlement summary copied to clipboard', 'success');
    } catch {
      showToast(
        'Copy Failed',
        'This browser blocked clipboard access. Use the WhatsApp share or the JPG export instead.',
        'error'
      );
    }
  };

  const handleShareWhatsApp = () => {
    const text = `*DENTAL CLINIC SETTLEMENT RECEIPT*
----------------------------------------
*Settlement ID:* ${settlement.settlementId}
*Date:* ${weekdayNameDateKey(settlement.settlementDate)} ${displayDateKey(settlement.settlementDate)}
*Clinic:* ${settings.clinicName}
*Doctor:* ${settings.doctorName || '—'}
*Period:* ${weekdayNameDateKey(settlement.periodFrom)} ${displayDateKey(settlement.periodFrom)} to ${weekdayNameDateKey(settlement.periodTo)} ${displayDateKey(settlement.periodTo)}
*Patients Settled:* ${settlement.patientCount}

*FINANCIAL BREAKDOWN:*
• *Doctor ${settings.sharePercentage || 40}% Share:* ${currency} ${formatNumber(settlement.periodShare)}
• *Previous Due:* ${currency} ${formatNumber(settlement.previousDue)}
• *Total Payable:* ${currency} ${formatNumber(settlement.totalPayable)}
• *Amount Paid by Clinic:* ${currency} ${formatNumber(settlement.amountReceived)}
• *Due Carried Forward:* ${currency} ${formatNumber(settlement.dueBalance)}
• *Confirmation:* ${outcomeLine}
${settlement.remarks ? `• *Notes:* ${settlement.remarks}\n` : ''}----------------------------------------
_Generated electronically by HishApp (hishapp1.web.app)_`;

    const waUrl = `https://api.whatsapp.com/send?text=${encodeURIComponent(text)}`;
    const a = document.createElement('a');
    a.href = waUrl;
    a.target = '_blank';
    a.rel = 'noopener noreferrer';
    document.body.appendChild(a);
    a.click();
    setTimeout(() => {
      try {
        if (document.body.contains(a)) {
          document.body.removeChild(a);
        }
      } catch {}
    }, 500);
    showToast('WhatsApp Share', 'Settlement receipt opened in WhatsApp', 'success');
  };

  /** Saves / shares this settlement as a formal JPG statement image. */
  const handleExportImage = async () => {
    try {
      setIsExportingImage(true);
      const result = await exportSettlementAsImage(settlement, settings);
      if (result.outcome === 'cancelled') return; // share sheet dismissed on purpose
      showToast(
        result.outcome === 'shared' ? 'Statement Image Shared' : 'Statement Image Saved',
        result.outcome === 'shared'
          ? `${result.fileName} is ready in the share sheet.`
          : `${result.fileName} downloaded to this device.`,
        'success'
      );
    } catch (err: any) {
      console.error('Statement image export error:', err);
      showToast('Image Export Failed', err?.message || 'Could not create the image', 'error');
    } finally {
      setIsExportingImage(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/40 backdrop-blur-sm animate-in fade-in">
      <div className="ios-glass bg-white/95 rounded-3xl p-6 w-full max-w-md shadow-2xl space-y-5">
        <div className="flex items-center justify-between pb-3 border-b border-slate-100">
          <div className="flex items-center gap-2 text-emerald-600">
            <CheckCircle2 className="w-5 h-5" />
            <h3 className="text-base font-bold text-slate-900">Settlement Finalized</h3>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 rounded-full text-slate-400 hover:text-slate-700 hover:bg-slate-100 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Digital Receipt Card */}
        <div className="p-5 rounded-2xl bg-slate-50 border border-slate-200/80 space-y-4 font-sans text-xs">
          <div className="text-center pb-3 border-b border-dashed border-slate-300 flex flex-col items-center">
            {settings.clinicLogo && (
              <img
                src={settings.clinicLogo}
                alt={settings.clinicName || 'Clinic Logo'}
                className="w-10 h-10 object-contain mb-1.5 rounded-lg"
                onError={(e) => {
                  (e.currentTarget as HTMLElement).style.display = 'none';
                }}
              />
            )}
            <span className="text-[10px] uppercase font-bold text-indigo-600 tracking-wider">
              {settings.clinicName || 'Yashfin Dental Care'}
            </span>
            <h4 className="text-base font-black text-slate-900 mt-0.5">
              Clinical Payout Settlement
            </h4>
            <div className="font-mono text-xs font-bold text-slate-500 mt-1">
              {settlement.settlementId}
            </div>
          </div>

          <div className="space-y-2">
            <div className="flex justify-between text-slate-600">
              <span>Doctor:</span>
              <span className="font-semibold text-slate-900">{settings.doctorName || '—'}</span>
            </div>
            <div className="flex justify-between text-slate-600">
              <span>Date Range:</span>
              <span className="font-medium text-slate-800">
                {weekdayNameDateKey(settlement.periodFrom)} {displayDateKey(settlement.periodFrom)} ~{' '}
                {weekdayNameDateKey(settlement.periodTo)} {displayDateKey(settlement.periodTo)}
              </span>
            </div>
            <div className="flex justify-between text-slate-600">
              <span>Patients Count:</span>
              <span className="font-semibold text-slate-900">{settlement.patientCount} visits</span>
            </div>
          </div>

          <div className="pt-2 border-t border-slate-200 space-y-2">
            <div className="flex justify-between text-slate-600">
              <span>Period Doctor Share (40%):</span>
              <span className="font-bold text-slate-800">
                {currency} {formatNumber(settlement.periodShare)}
              </span>
            </div>
            <div className="flex justify-between text-slate-600">
              <span>Carried-over Due:</span>
              <span className="font-semibold text-amber-700">
                {currency} {formatNumber(settlement.previousDue)}
              </span>
            </div>
            <div className="flex justify-between font-bold text-slate-900 pt-1 border-t border-slate-200">
              <span>Total Payable:</span>
              <span className="text-indigo-600 font-black">
                {currency} {formatNumber(settlement.totalPayable)}
              </span>
            </div>
            <div className="flex justify-between text-slate-600">
              <span>Amount Received:</span>
              <span className="font-bold text-emerald-600">
                {currency} {formatNumber(settlement.amountReceived)}
              </span>
            </div>
            <div className="flex justify-between font-black text-slate-900 pt-1 border-t border-slate-300">
              <span>Next Carry-Forward Due:</span>
              <span
                className={`${
                  settlement.dueBalance > 0 ? 'text-amber-600' : 'text-slate-800'
                }`}
              >
                {currency} {formatNumber(settlement.dueBalance)}
              </span>
            </div>
          </div>

          {/* How the batch was confirmed (tick required when the payment did not match claimable) */}
          <div
            className={`flex items-start gap-2 p-2.5 rounded-xl border text-[11px] font-semibold ${
              hasDue
                ? 'bg-amber-50/80 border-amber-200 text-amber-800'
                : 'bg-emerald-50/80 border-emerald-200 text-emerald-800'
            }`}
          >
            <BadgeCheck className="w-3.5 h-3.5 shrink-0 mt-0.5" />
            <div>
              <p className="leading-tight">
                {hasDue
                  ? `Settlement done with due amount ${currency} ${formatNumber(settlement.dueBalance)}`
                  : 'Settlement Cleared with no due'}
              </p>
              {!hasDue && writtenOff > 0 && (
                <p className="text-[10px] font-medium text-emerald-700 mt-0.5">
                  {currency} {formatNumber(writtenOff)} waived by mutual agreement on a round figure —
                  nothing shows in the dashboard due cards.
                </p>
              )}
              {hasDue && (
                <p className="text-[10px] font-medium text-amber-700 mt-0.5">
                  This balance carries forward to the next settlement cycle.
                </p>
              )}
            </div>
          </div>

          {settlement.remarks && (
            <div className="pt-2 border-t border-dashed border-slate-300 text-slate-500 italic">
              Note: {settlement.remarks}
            </div>
          )}
        </div>

        {/* Action Buttons */}
        <div className="space-y-2">
          {/* Direct WhatsApp Share Button */}
          <button
            type="button"
            onClick={handleShareWhatsApp}
            className="w-full py-2.5 rounded-xl bg-gradient-to-r from-emerald-500 via-emerald-600 to-green-600 hover:from-emerald-600 hover:to-green-700 text-white text-xs font-bold flex items-center justify-center gap-2 shadow-md shadow-emerald-500/25 active:scale-95 transition"
            title="Send formatted settlement receipt directly via WhatsApp"
          >
            <svg className="w-4 h-4 fill-current shrink-0" viewBox="0 0 24 24">
              <path d="M17.472 14.382c-.297-.149-1.758-.867-2.03-.967-.273-.099-.471-.148-.67.15-.197.297-.767.966-.94 1.164-.173.199-.347.223-.644.075-.297-.15-1.255-.463-2.39-1.475-.883-.788-1.48-1.761-1.653-2.059-.173-.297-.018-.458.13-.606.134-.133.298-.347.446-.52.149-.174.198-.298.298-.497.099-.198.05-.371-.025-.52-.075-.149-.669-1.612-.916-2.207-.242-.579-.487-.5-.669-.51-.173-.008-.371-.01-.57-.01-.198 0-.52.074-.792.372-.272.297-1.04 1.016-1.04 2.479 0 1.462 1.065 2.875 1.213 3.074.149.198 2.096 3.2 5.077 4.487.709.306 1.262.489 1.694.625.712.227 1.36.195 1.871.118.571-.085 1.758-.719 2.006-1.413.248-.694.248-1.289.173-1.413-.074-.124-.272-.198-.57-.347m-5.421 7.403h-.004a9.87 9.87 0 01-5.031-1.378l-.361-.214-3.741.982.998-3.648-.235-.374a9.86 9.86 0 01-1.51-5.26c.001-5.45 4.436-9.884 9.888-9.884 2.64 0 5.122 1.03 6.988 2.898a9.825 9.825 0 012.893 6.994c-.003 5.45-4.437 9.884-9.885 9.884m8.413-18.297A11.815 11.815 0 0012.05 0C5.495 0 .16 5.335.157 11.892c0 2.096.547 4.142 1.588 5.945L0 24l6.335-1.662c1.746.953 3.71 1.455 5.711 1.456h.005c6.554 0 11.89-5.335 11.893-11.893a11.821 11.821 0 00-3.48-8.413z"/>
            </svg>
            <span>Direct WhatsApp Share</span>
          </button>

          <button
            type="button"
            onClick={() => void handleExportImage()}
            disabled={isExportingImage}
            className="btn-gradient btn-gradient--sky w-full py-2.5 rounded-xl text-white text-xs font-bold flex items-center justify-center gap-1.5 disabled:opacity-60 active:scale-95 transition"
            title="Save this settlement as a JPG image"
          >
            {isExportingImage ? (
              <Loader2 className="w-3.5 h-3.5 animate-spin" />
            ) : (
              <ImageDown className="w-3.5 h-3.5" />
            )}
            <span>{isExportingImage ? 'Preparing Image...' : 'Save Statement as JPG'}</span>
          </button>

          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={() => void handleCopySummary()}
              className="flex-1 py-2.5 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 text-xs font-bold flex items-center justify-center gap-1.5 transition active:scale-95"
            >
              <Copy className="w-3.5 h-3.5" />
              <span>Copy Receipt</span>
            </button>
            <button
              onClick={onClose}
              className="btn-gradient flex-1 py-2.5 rounded-xl text-white text-xs font-bold"
            >
              Done
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
