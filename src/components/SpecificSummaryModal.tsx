import React, { useState, useMemo } from 'react';
import {
  Download,
  Printer,
  X,
  CalendarRange,
} from 'lucide-react';
import { ClinicSettings, PatientEntry, Settlement } from '../types';
import { exportRangeSummaryPDF, generateRangeSummaryData } from '../utils/pdfExport';
import { formatDateKey, todayDateKey } from '../utils/dateUtils';

interface SpecificSummaryModalProps {
  isOpen: boolean;
  onClose: () => void;
  entries: PatientEntry[];
  settlements: Settlement[];
  settings: ClinicSettings;
  showToast: (title: string, desc?: string, type?: 'success' | 'info' | 'warning' | 'error') => void;
}

export const SpecificSummaryModal: React.FC<SpecificSummaryModalProps> = ({
  isOpen,
  onClose,
  entries,
  settlements,
  settings,
  showToast,
}) => {
  const currency = settings.currencySymbol || '৳';
  const shareRate = settings.sharePercentage || 40;
  const formatNumber = (num: number) => new Intl.NumberFormat('en-BD').format(Math.round(num));

  // Default range: first day of the current month → today
  const now = new Date();
  const defaultFrom = formatDateKey(new Date(now.getFullYear(), now.getMonth(), 1));
  const defaultTo = todayDateKey(now);

  const [fromDate, setFromDate] = useState<string>(defaultFrom);
  const [toDate, setToDate] = useState<string>(defaultTo);
  const [isExporting, setIsExporting] = useState<boolean>(false);

  // Latest settlement carry-forward debt
  const latestSettlement = settlements.length > 0 ? settlements[0] : null;
  const previousDue = latestSettlement ? latestSettlement.dueBalance : 0;

  // ISO `YYYY-MM-DD` keys compare correctly as plain strings
  const isRangeValid = fromDate <= toDate;

  // Compute statement data for the selected period
  const summaryData = useMemo(() => {
    if (!isRangeValid) return null;
    return generateRangeSummaryData(fromDate, toDate, entries, settlements, previousDue);
  }, [isRangeValid, fromDate, toDate, entries, settlements, previousDue]);

  if (!isOpen) return null;

  const handleDownloadPDF = () => {
    if (!summaryData) {
      showToast('Invalid Date Range', 'The first date must be on or before the last date.', 'warning');
      return;
    }
    try {
      setIsExporting(true);
      exportRangeSummaryPDF(summaryData, settings, fromDate, toDate);
      showToast(
        'PDF Exported Successfully!',
        `Saved Dental_Settlement_Statement_${fromDate}_to_${toDate}.pdf`,
        'success'
      );
    } catch (err: any) {
      console.error('PDF Export error:', err);
      showToast('Export Error', err?.message || 'Failed to generate PDF', 'error');
    } finally {
      setIsExporting(false);
    }
  };

  const handlePrint = () => {
    window.print();
  };

  const handleShareWhatsApp = () => {
    if (!summaryData) return;
    const text = `*SPECIFIC CLINICAL SETTLEMENT STATEMENT*
----------------------------------------
*Period:* ${fromDate} to ${toDate}
*Clinic:* ${settings.clinicName || 'Clinic'}
*Doctor:* ${settings.doctorName || '—'}
*Share Rate:* ${shareRate}%

*SUMMARY OVERVIEW:*
• *Total Patients:* ${summaryData.patientCount}
• *Gross Revenue:* ${currency} ${formatNumber(summaryData.totalGross)}
• *Doctor ${shareRate}% Share:* ${currency} ${formatNumber(summaryData.totalDoctorShare)}
• *Carried-over Due:* ${currency} ${formatNumber(summaryData.previousDue)}
• *Settled to Doctor:* ${currency} ${formatNumber(summaryData.amountReceivedByClinic)}
• *Closing Due Balance:* ${currency} ${formatNumber(summaryData.outstandingBalance)}
----------------------------------------
_Generated by HishApp (hishapp1.web.app)_`;

    const waUrl = `https://api.whatsapp.com/send?text=${encodeURIComponent(text)}`;
    const a = document.createElement('a');
    a.href = waUrl;
    a.target = '_blank';
    a.rel = 'noopener noreferrer';
    document.body.appendChild(a);
    a.click();
    setTimeout(() => {
      try {
        if (document.body.contains(a)) {
          document.body.removeChild(a);
        }
      } catch {}
    }, 500);
    showToast('WhatsApp Share', 'Specific period statement opened in WhatsApp', 'success');
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-4 bg-slate-900/40 backdrop-blur-sm animate-in fade-in overflow-y-auto">
      <div className="ios-glass bg-white/95 rounded-3xl p-5 sm:p-6 w-full max-w-2xl shadow-2xl space-y-5 my-auto max-h-[92vh] flex flex-col">
        {/* Header */}
        <div className="flex items-center justify-between pb-3 border-b border-slate-100 shrink-0">
          <div className="flex items-center gap-2.5">
            <div className="w-10 h-10 rounded-2xl bg-emerald-50 border border-emerald-100 text-emerald-600 flex items-center justify-center">
              <CalendarRange className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-base sm:text-lg font-bold text-slate-900 leading-tight">
                Specific Clinical Settlement Statement
              </h3>
              <p className="text-xs text-slate-500">
                Official statement &amp; formatted PDF report for a custom date range
              </p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="p-1.5 rounded-full text-slate-400 hover:text-slate-700 hover:bg-slate-100 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Date Range Selector Bar */}
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 p-3.5 rounded-2xl bg-slate-50 border border-slate-200/70 shrink-0">
          <div className="flex items-center gap-2">
            <CalendarRange className="w-4 h-4 text-emerald-600" />
            <span className="text-xs font-bold text-slate-700">Statement Period:</span>
          </div>

          <div className="flex items-center gap-2">
            <div className="flex flex-col">
              <label className="text-[10px] font-bold text-slate-500 uppercase tracking-wide">
                First Date
              </label>
              <input
                type="date"
                value={fromDate}
                max={toDate}
                onChange={(e) => setFromDate(e.target.value)}
                className="px-3 py-1.5 rounded-xl bg-white border border-slate-200 text-xs font-bold text-slate-800 focus:border-emerald-500 outline-none"
              />
            </div>

            <span className="text-xs font-bold text-slate-400 mt-4">→</span>

            <div className="flex flex-col">
              <label className="text-[10px] font-bold text-slate-500 uppercase tracking-wide">
                Last Date
              </label>
              <input
                type="date"
                value={toDate}
                min={fromDate}
                onChange={(e) => setToDate(e.target.value)}
                className="px-3 py-1.5 rounded-xl bg-white border border-slate-200 text-xs font-bold text-slate-800 focus:border-emerald-500 outline-none"
              />
            </div>
          </div>
        </div>

        {!isRangeValid && (
          <div className="p-3 rounded-2xl bg-amber-50 border border-amber-200 text-xs font-bold text-amber-800 shrink-0">
            The first date must be on or before the last date. Please adjust the period.
          </div>
        )}

        {/* Scrollable Report Preview */}
        {summaryData && (
        <div className="flex-1 overflow-y-auto space-y-4 pr-1">
          {/* Executive KPI Grid */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-2.5">
            {/* KPI 1: Doctor 40% Share */}
            <div className="p-3.5 rounded-2xl bg-indigo-50/70 border border-indigo-100">
              <span className="text-[10px] font-bold text-indigo-600 uppercase tracking-wider block">
                Doctor's Share ({shareRate}%)
              </span>
              <div className="text-lg font-black text-indigo-900 mt-1">
                {currency} {formatNumber(summaryData.totalDoctorShare)}
              </div>
              <span className="text-[10px] text-indigo-600/80">From {currency} {formatNumber(summaryData.totalGross)}</span>
            </div>

            {/* KPI 2: Patients Treated */}
            <div className="p-3.5 rounded-2xl bg-sky-50/70 border border-sky-100">
              <span className="text-[10px] font-bold text-sky-600 uppercase tracking-wider block">
                Patients Treated
              </span>
              <div className="text-lg font-black text-sky-900 mt-1">
                {summaryData.patientCount} <span className="text-xs font-semibold">Visits</span>
              </div>
              <span className="text-[10px] text-sky-600/80">In selected period</span>
            </div>

            {/* KPI 3: Clinic Received */}
            <div className="p-3.5 rounded-2xl bg-emerald-50/70 border border-emerald-100">
              <span className="text-[10px] font-bold text-emerald-600 uppercase tracking-wider block">
                Cleared by Clinic
              </span>
              <div className="text-lg font-black text-emerald-900 mt-1">
                {currency} {formatNumber(summaryData.amountReceivedByClinic)}
              </div>
              <span className="text-[10px] text-emerald-600/80">Disbursed Payout</span>
            </div>

            {/* KPI 4: Outstanding Balance */}
            <div className="p-3.5 rounded-2xl bg-amber-50/80 border border-amber-200">
              <span className="text-[10px] font-bold text-amber-800 uppercase tracking-wider block">
                Outstanding Due
              </span>
              <div className="text-lg font-black text-amber-900 mt-1">
                {currency} {formatNumber(summaryData.outstandingBalance)}
              </div>
              <span className="text-[10px] text-amber-700/80">Carry-forward due</span>
            </div>
          </div>

          {/* Report Metadata Strip */}
          <div className="p-3.5 rounded-2xl bg-white border border-slate-200/80 text-xs text-slate-600 space-y-1.5 shadow-2xs">
            <div className="flex justify-between items-center">
              <span className="font-semibold text-slate-700">Clinic:</span>
              <div className="flex items-center gap-1.5">
                {settings.clinicLogo && (
                  <img
                    src={settings.clinicLogo}
                    alt={settings.clinicName || 'Clinic Logo'}
                    className="w-4 h-4 object-contain rounded"
                    onError={(e) => {
                      (e.currentTarget as HTMLElement).style.display = 'none';
                    }}
                  />
                )}
                <span className="font-bold text-slate-900">{settings.clinicName}</span>
              </div>
            </div>
            <div className="flex justify-between items-center">
              <span className="font-semibold text-slate-700">Attending Surgeon:</span>
              <span className="font-bold text-slate-900">{settings.doctorName || '—'}</span>
            </div>
            <div className="flex justify-between items-center">
              <span className="font-semibold text-slate-700">Reporting Range:</span>
              <span className="text-slate-800">{summaryData.periodStart} to {summaryData.periodEnd}</span>
            </div>
            <div className="flex justify-between items-center">
              <span className="font-semibold text-slate-700">Prior Carry-In Due:</span>
              <span className="text-amber-700 font-semibold">{currency} {formatNumber(summaryData.previousDue)}</span>
            </div>
          </div>

          {/* Procedure Distribution Table Preview */}
          <div className="space-y-2">
            <h4 className="text-xs font-bold text-slate-900 uppercase tracking-wider">
              Procedure Earnings Breakdown
            </h4>

            {summaryData.procedureBreakdown.length === 0 ? (
              <div className="p-4 text-center text-slate-400 text-xs bg-slate-50 rounded-xl">
                No patient procedures recorded in this period.
              </div>
            ) : (
              <div className="overflow-x-auto rounded-2xl border border-slate-200">
                <table className="w-full text-left text-xs">
                  <thead className="bg-slate-100/80 text-slate-700 text-[11px] font-bold">
                    <tr>
                      <th className="py-2 px-3">Treatment</th>
                      <th className="py-2 px-3 text-center">Visits</th>
                      <th className="py-2 px-3 text-right">Gross Bill</th>
                      <th className="py-2 px-3 text-right">Doctor {shareRate}%</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-100">
                    {summaryData.procedureBreakdown.map((p) => (
                      <tr key={p.name} className="hover:bg-slate-50/50">
                        <td className="py-2 px-3 font-semibold text-slate-800">{p.name}</td>
                        <td className="py-2 px-3 text-center text-slate-600">{p.count}</td>
                        <td className="py-2 px-3 text-right text-slate-600">
                          {currency} {formatNumber(p.gross)}
                        </td>
                        <td className="py-2 px-3 text-right font-bold text-indigo-600">
                          {currency} {formatNumber(p.doctorShare)}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </div>
        </div>
        )}

        {/* Footer Actions */}
        <div className="pt-3 border-t border-slate-100 flex flex-wrap items-center justify-end gap-2.5 shrink-0">
          <button
            type="button"
            onClick={handleShareWhatsApp}
            disabled={!summaryData}
            className="px-3.5 py-2.5 rounded-xl bg-gradient-to-r from-emerald-500 via-emerald-600 to-green-600 hover:from-emerald-600 hover:to-green-700 text-white text-xs font-bold flex items-center gap-1.5 shadow-sm shadow-emerald-500/25 transition active:scale-95 disabled:opacity-60 disabled:cursor-not-allowed"
            title="Share statement directly to WhatsApp"
          >
            <svg className="w-4 h-4 fill-current shrink-0" viewBox="0 0 24 24">
              <path d="M17.472 14.382c-.297-.149-1.758-.867-2.03-.967-.273-.099-.471-.148-.67.15-.197.297-.767.966-.94 1.164-.173.199-.347.223-.644.075-.297-.15-1.255-.463-2.39-1.475-.883-.788-1.48-1.761-1.653-2.059-.173-.297-.018-.458.13-.606.134-.133.298-.347.446-.52.149-.174.198-.298.298-.497.099-.198.05-.371-.025-.52-.075-.149-.669-1.612-.916-2.207-.242-.579-.487-.5-.669-.51-.173-.008-.371-.01-.57-.01-.198 0-.52.074-.792.372-.272.297-1.04 1.016-1.04 2.479 0 1.462 1.065 2.875 1.213 3.074.149.198 2.096 3.2 5.077 4.487.709.306 1.262.489 1.694.625.712.227 1.36.195 1.871.118.571-.085 1.758-.719 2.006-1.413.248-.694.248-1.289.173-1.413-.074-.124-.272-.198-.57-.347m-5.421 7.403h-.004a9.87 9.87 0 01-5.031-1.378l-.361-.214-3.741.982.998-3.648-.235-.374a9.86 9.86 0 01-1.51-5.26c.001-5.45 4.436-9.884 9.888-9.884 2.64 0 5.122 1.03 6.988 2.898a9.825 9.825 0 012.893 6.994c-.003 5.45-4.437 9.884-9.885 9.884m8.413-18.297A11.815 11.815 0 0012.05 0C5.495 0 .16 5.335.157 11.892c0 2.096.547 4.142 1.588 5.945L0 24l6.335-1.662c1.746.953 3.71 1.455 5.711 1.456h.005c6.554 0 11.89-5.335 11.893-11.893a11.821 11.821 0 00-3.48-8.413z"/>
            </svg>
            <span>WhatsApp Share</span>
          </button>

          <button
            type="button"
            onClick={handlePrint}
            className="px-3.5 py-2.5 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 text-xs font-bold flex items-center gap-1.5 transition active:scale-95"
          >
            <Printer className="w-4 h-4 text-slate-600" />
            <span>Print Report</span>
          </button>

          <button
            type="button"
            onClick={handleDownloadPDF}
            disabled={isExporting || !summaryData}
            className="btn-gradient btn-gradient--emerald px-5 py-2.5 rounded-xl text-white text-xs font-bold flex items-center gap-2 disabled:opacity-60 disabled:cursor-not-allowed"
          >
            <Download className="w-4 h-4" />
            <span>{isExporting ? 'Generating PDF...' : 'Download Formatted PDF'}</span>
          </button>
        </div>
      </div>
    </div>
  );
};
